def _ts(v):
    if isinstance(v, (int, float)):
        return v / 1000 if v > 1e11 else float(v)
    if isinstance(v, str) and v:
        from datetime import datetime
        try:
            return datetime.fromisoformat(v.replace("Z", "+00:00")).timestamp()
        except ValueError:
            return None
    return None


def _like(t):
    return "%" + t.replace("\\", "\\\\").replace("%", "\\%").replace("_", "\\_") + "%"


def search(q, providers=None, include_archived=False, limit=30, dm=None, project=None):
    """q: list of positive terms (AND) and negatives in q['not']. Returns list of dicts."""
    terms, negs = q.get("terms", []), q.get("not", [])
    con = connect()
    where, args = ["1=1"], []
    if not include_archived:
        where.append("t.archived=0")
    if providers:
        where.append("t.provider IN (%s)" % ",".join("?" * len(providers)))
        args += list(providers)
    if dm:
        where.append("t.modified BETWEEN ? AND ?")
        args += [dm[0], min(dm[1], 1e12)]
    if project:
        where.append("LOWER(t.project) LIKE ? ESCAPE '\\'")
        args.append(_like(project.lower()))
    for t in terms:
        if len(t) >= 3:
            from .content import fts_phrase
            sub, arg = "SELECT key FROM msgs WHERE msgs MATCH ?", fts_phrase([t])
        else:
            sub, arg = "SELECT key FROM msgs WHERE body LIKE ? ESCAPE '\\'", _like(t)
        where.append("(t.title LIKE ? ESCAPE '\\' OR t.project LIKE ? ESCAPE '\\' OR t.key IN (" + sub + "))")
        args += [_like(t), _like(t), arg]
    for t in negs:
        where.append("NOT (t.title LIKE ? ESCAPE '\\' OR t.key IN (SELECT key FROM msgs WHERE body LIKE ? ESCAPE '\\'))")
        args += [_like(t)] * 2
    sql = ("SELECT t.key, t.provider, t.id, t.title, t.project, t.modified, t.archived, t.desktop_id, t.excerpt, t.messages "
           "FROM topics t WHERE " + " AND ".join(where) + " ORDER BY t.modified DESC")
    rows = con.execute(sql, args).fetchall()
    total = len(rows)
    out = []
    now = time.time()
    for key, prov, tid, title, project_, mod, arch, did, excerpt, nmsg in rows:
        title_hit = sum(1 for t in terms if t.lower() in (title or "").lower())
        age = now - (mod or 0)
        score = title_hit * 300 + (60 if age < 86400 else 45 if age < 604800 else 30 if age < 2592000 else 0)
        out.append([score, mod or 0, key, prov, tid, title, project_, arch, did, excerpt, nmsg])
    out.sort(key=lambda r: (-r[0], -r[1]))
    res = []
    for score, mod, key, prov, tid, title, project_, arch, did, excerpt, nmsg in out[:limit]:
        snip = ""
        if terms:
            r = con.execute("SELECT body FROM msgs WHERE key=? AND body LIKE ? ESCAPE '\\' LIMIT 1", (key, _like(terms[0]))).fetchone()
            if r:
                from .content import snippet
                snip = snippet(r[0], terms, 60)
        t = {"key": key, "source": PROVIDER_ZH[prov], "provider": prov, "id": tid, "title": title or "(无标题)",
             "project": project_, "modified": round(mod), "archived": bool(arch), "messages": nmsg,
             "snippet": snip or (excerpt or "")[:160].replace("\n", " ")}
        t.update(actions(prov, tid, project_, did))
        res.append(t)
    con.close()
    return res, total


def actions(provider, tid, project, desktop_id):
    q = shlex.quote
    out = {}
    if provider == "claude":
        if desktop_id and re.match(r"^local_[A-Za-z0-9-]{1,64}$", desktop_id):
            out["open_url"] = "claude://claude.ai/epitaxy/" + desktop_id
        if UUID_RE.match(tid):
            out["resume"] = (f"cd {q(project)} && " if project else "") + f"claude --resume {q(tid)}"
        elif "open_url" in out:
            out["resume"] = "open " + q(out["open_url"])
    elif provider == "codex":
        if UUID_RE.match(tid):
            out["open_url"] = "codex://threads/" + tid
        out["resume"] = (f"cd {q(project)} && " if project else "") + f"codex resume {q(tid)}"
    elif provider == "workbuddy":
        out["open_url"] = "workbuddy://chat/" + tid
        out["resume"] = "open " + q(out["open_url"])
    return out


def get(key):
    con = connect()
    r = con.execute("SELECT provider, id, title, project, desktop_id, transcript FROM topics WHERE key=?", (key,)).fetchone()
    con.close()
    if not r:
        return None
    d = {"provider": r[0], "id": r[1], "title": r[2], "project": r[3], "transcript": r[5]}
    d.update(actions(r[0], r[1], r[3], r[4]))
    return d


