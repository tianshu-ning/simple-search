"""搜索本机 Claude Code、Codex 和 WorkBuddy 对话。

以只读方式读取本机会话。索引保存在 <data>/topics.sqlite，未变化的日志直接跳过。
"""
import glob
import hashlib
import json
import os
import re
import shlex
import sqlite3
import time

from .common import HOME, IS_MAC, data_dir, which

PROVIDERS = ("claude", "codex", "workbuddy")
PROVIDER_ZH = {"claude": "Claude Code", "codex": "Codex", "workbuddy": "WorkBuddy"}
UUID_RE = re.compile(r"^[0-9a-fA-F]{8}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{4}-[0-9a-fA-F]{12}$")
SAFE_ID = re.compile(r"^[A-Za-z0-9_-]{1,256}$")

SCHEMA = """
PRAGMA journal_mode=WAL;
CREATE TABLE IF NOT EXISTS topics(key TEXT PRIMARY KEY, provider TEXT, id TEXT, title TEXT, project TEXT,
  modified REAL, archived INTEGER DEFAULT 0, desktop_id TEXT DEFAULT '', transcript TEXT DEFAULT '',
  excerpt TEXT DEFAULT '', messages INTEGER DEFAULT 0, seen REAL);
CREATE VIRTUAL TABLE IF NOT EXISTS msgs USING fts5(key UNINDEXED, role UNINDEXED, body, tokenize='trigram');
CREATE TABLE IF NOT EXISTS cursors(path TEXT PRIMARY KEY, key TEXT, size INTEGER, mtime REAL, offset INTEGER, head TEXT);
"""


def db_path():
    return os.path.join(data_dir(), "topics.sqlite")


def connect():
    con = sqlite3.connect(db_path(), timeout=30)
    try:
        con.executescript(SCHEMA)
        if con.execute("PRAGMA user_version").fetchone()[0] == 0:
            # 在第一次读取旧索引前清理已移除来源的记录，避免搜索和查看仍返回旧会话。
            with con:
                con.execute("DELETE FROM msgs WHERE key IN (SELECT key FROM topics WHERE provider='deepseek')")
                con.execute("DELETE FROM cursors WHERE key IN (SELECT key FROM topics WHERE provider='deepseek')")
                con.execute("DELETE FROM topics WHERE provider='deepseek'")
                con.execute("PRAGMA user_version=1")
    except sqlite3.Error:
        con.close()
        raise
    return con


# ------------------------------------------------------------------ locations

def _env_dir(var, default):
    v = os.environ.get(var)
    return os.path.expanduser(v) if v else os.path.join(HOME, default)


def locations():
    loc = {
        "claude": _env_dir("CLAUDE_CONFIG_DIR", ".claude"),
        "codex": _env_dir("CODEX_HOME", ".codex"),
        "workbuddy": _env_dir("WORKBUDDY_CONFIG_DIR", ".workbuddy"),
        "claude_desktop": [],
    }
    for app in ("Claude", "Claude-3p"):
        d = os.path.join(HOME, "Library/Application Support", app, "claude-code-sessions")
        if os.path.isdir(d):
            loc["claude_desktop"].append(d)
    return loc


def installed(provider):
    """Read-only presence check: app bundle, CLI on PATH, or saved data."""
    loc = locations()
    if provider == "claude":
        return bool(which("claude") or os.path.isdir(os.path.join(loc["claude"], "projects")) or loc["claude_desktop"]
                    or (IS_MAC and os.path.isdir("/Applications/Claude.app")))
    if provider == "codex":
        return bool(which("codex") or glob.glob(os.path.join(loc["codex"], "state_*.sqlite"))
                    or os.path.isdir(os.path.join(loc["codex"], "sessions")) or (IS_MAC and os.path.isdir("/Applications/Codex.app")))
    if provider == "workbuddy":
        return bool(os.path.exists(os.path.join(loc["workbuddy"], "workbuddy.db"))
                    or (IS_MAC and os.path.isdir("/Applications/WorkBuddy.app")))
    return False


def enabled_providers(cfg, only=None):
    t = cfg.get("topics") or {}
    out = []
    for p in PROVIDERS:
        if only and p not in only:
            continue
        flag = t.get(p)
        if flag is True or (flag is None and installed(p)) or (only and flag is not False):
            out.append(p)
    return out


# ------------------------------------------------------------------ message parsing

_SYS_TAGS = re.compile(r"<(system-reminder|command-[a-z-]+|local-command-[a-z-]+|environment_context|user_instructions|"
                       r"permissions instructions|ide_[a-z_]+)\b[^>]*>.*?</\1>", re.S)
_NOISE_PREFIX = ("<environment_context>", "<user_instructions>", "# AGENTS.md instructions", "<permissions instructions>",
                 "Caveat: The messages below were generated by the user while running local commands")


def _text(value):
    if isinstance(value, str):
        return value
    if isinstance(value, list):
        out = []
        for b in value:
            if isinstance(b, dict) and b.get("type") in ("text", "input_text", "output_text") and isinstance(b.get("text"), str):
                out.append(b["text"])
            elif isinstance(b, str):
                out.append(b)
        return "\n".join(out)
    return ""


def _clean(body, user):
    if user:
        body = _SYS_TAGS.sub("", body)
        if body.lstrip().startswith(_NOISE_PREFIX):
            return ""
    return body.strip()


def claude_message(o):
    if o.get("isMeta") or o.get("isSidechain") or o.get("type") not in ("user", "assistant"):
        return None
    m = o.get("message")
    if not isinstance(m, dict):
        return None
    user = o["type"] == "user"
    body = _clean(_text(m.get("content")), user)
    return (body, user) if body else None


def codex_message(o):
    t = o.get("type")
    if t == "userMessage":
        body = _clean(_text(o.get("content")), True)
        return (body, True) if body else None
    if t == "agentMessage" and isinstance(o.get("text"), str):
        return (o["text"].strip(), False) if o["text"].strip() else None
    if t == "response_item":
        p = o.get("payload") or {}
        if p.get("type") == "message" and p.get("role") in ("user", "assistant"):
            user = p["role"] == "user"
            body = _clean(_text(p.get("content")), user)
            return (body, user) if body else None
    return None


def workbuddy_message(o):
    if o.get("type") != "message" or o.get("role") not in ("user", "assistant"):
        return None
    pd = o.get("providerData") or {}
    user = o["role"] == "user"
    if user and pd.get("isMeta"):
        return None
    body = _clean(_text(o.get("contentText") or o.get("content")), user)
    return (body, user) if body else None


