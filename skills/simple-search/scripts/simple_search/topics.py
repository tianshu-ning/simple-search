class Syncer:
    def __init__(self, con):
        self.con = con
        self.now = time.time()
        self.stats = {"topics": 0, "files_read": 0, "files_skipped": 0, "messages": 0}
        self.errors = {}

    def upsert(self, key, provider, tid, title="", project="", modified=0, archived=False, desktop_id="",
               transcript="", excerpt=""):
        cur = self.con.execute("SELECT title, project, excerpt, modified FROM topics WHERE key=?", (key,)).fetchone()
        if cur:
            title = title or cur[0]
            project = project or cur[1]
            excerpt = excerpt or cur[2]
            modified = max(modified or 0, cur[3] or 0)
        self.con.execute("""INSERT INTO topics(key, provider, id, title, project, modified, archived, desktop_id, transcript, excerpt, seen)
            VALUES(?,?,?,?,?,?,?,?,?,?,?) ON CONFLICT(key) DO UPDATE SET title=excluded.title, project=excluded.project,
            modified=excluded.modified, archived=excluded.archived,
            desktop_id=CASE WHEN excluded.desktop_id!='' THEN excluded.desktop_id ELSE topics.desktop_id END,
            transcript=CASE WHEN excluded.transcript!='' THEN excluded.transcript ELSE topics.transcript END,
            excerpt=excluded.excerpt, seen=excluded.seen""",
                         (key, provider, tid, (title or "")[:200].replace("\n", " "), project or "", modified or 0,
                          int(bool(archived)), desktop_id or "", transcript or "", (excerpt or "")[:240], self.now))
        self.stats["topics"] += 1

    def _head(self, f):
        f.seek(0)
        return hashlib.sha1(f.read(512)).hexdigest()

    def read_jsonl(self, path, key, parse, on_object=None, reset=None):
        """Incrementally index a JSONL transcript. Returns True if anything changed."""
        try:
            st = os.stat(path)
        except OSError:
            return False
        cur = self.con.execute("SELECT size, mtime, offset, head FROM cursors WHERE path=?", (path,)).fetchone()
        if cur and cur[0] == st.st_size and cur[1] == st.st_mtime:
            self.stats["files_skipped"] += 1
            return False
        with open(path, "rb") as f:
            head = self._head(f)
            offset = 0
            if cur and st.st_size >= cur[2] and cur[3] == head:
                offset = cur[2]       # append-only growth: continue after the last complete line
            if offset == 0:
                self.con.execute("DELETE FROM msgs WHERE key=?", (key,))
                if reset:
                    reset()
            f.seek(offset)
            data = f.read()
        self.stats["files_read"] += 1
        end = data.rfind(b"\n")
        complete = data[: end + 1] if end >= 0 else b""
        rows = []
        for line in complete.split(b"\n"):
            if not line.strip():
                continue
            try:
                o = json.loads(line)
            except ValueError:
                continue
            if not isinstance(o, dict):
                continue
            if on_object:
                on_object(o)
            m = parse(o)
            if m:
                rows.append((key, "user" if m[1] else "assistant", m[0][:200_000]))
        if rows:
            self.con.executemany("INSERT INTO msgs(key, role, body) VALUES(?,?,?)", rows)
            self.stats["messages"] += len(rows)
        self.con.execute("INSERT OR REPLACE INTO cursors VALUES(?,?,?,?,?,?)",
                         (path, key, st.st_size, st.st_mtime, offset + len(complete), head))
        self.con.execute("UPDATE topics SET messages=(SELECT COUNT(*) FROM msgs WHERE key=?) WHERE key=?", (key, key))
        return True

    def first_user(self, key):
        r = self.con.execute("SELECT body FROM msgs WHERE key=? AND role='user' LIMIT 1", (key,)).fetchone()
        return r[0] if r else ""

    def fill_title(self, key):
        r = self.con.execute("SELECT title, excerpt FROM topics WHERE key=?", (key,)).fetchone()
        if r and (not r[0] or not r[1]):
            first = self.first_user(key)
            title = r[0] or first[:120].replace("\n", " ")
            excerpt = r[1] or first[:240]
            self.con.execute("UPDATE topics SET title=?, excerpt=? WHERE key=?", (title, excerpt, key))


def sync_claude(s, loc):
    keys = set()
    # Desktop Code sessions: descriptors carry title, archive state and the CLI session id.
    for root in loc["claude_desktop"]:
        for p in glob.glob(os.path.join(root, "**", "*.json"), recursive=True):
            try:
                with open(p, encoding="utf-8") as f:
                    o = json.load(f)
            except (OSError, ValueError):
                continue
            if not isinstance(o, dict) or not o.get("sessionId"):
                continue
            did = o["sessionId"]
            tid = o.get("cliSessionId") or did
            key = "claude:" + tid
            s.upsert(key, "claude", tid, o.get("title") or "", o.get("cwd") or "",
                     _ts(o.get("lastActivityAt")) or _ts(o.get("createdAt")) or 0, bool(o.get("isArchived")),
                     did, "", (o.get("postTurnSummary") or "")[:240])
            keys.add(key)
    proj = os.path.join(loc["claude"], "projects")
    for p in glob.glob(os.path.join(proj, "*", "*.jsonl")):
        tid = os.path.basename(p)[:-6]
        if not UUID_RE.match(tid):
            continue
        key = "claude:" + tid
        meta = {"title": "", "cwd": "", "summary": ""}

        def on_obj(o, meta=meta):
            if not meta["cwd"] and isinstance(o.get("cwd"), str):
                meta["cwd"] = o["cwd"]
            t = o.get("customTitle") or o.get("aiTitle")
            if isinstance(t, str) and t:
                meta["title"] = t
            if o.get("type") == "summary" and isinstance(o.get("summary"), str):
                meta["summary"] = o["summary"]

        if key not in keys:
            s.upsert(key, "claude", tid, "", "", os.path.getmtime(p), False, "", p)
        reset = lambda key=key: s.con.execute(
            "UPDATE topics SET title='', excerpt='' WHERE key=? AND desktop_id=''", (key,))
        changed = s.read_jsonl(p, key, claude_message, on_obj, reset)
        if changed:
            title = meta["title"] or meta["summary"]
            s.con.execute("UPDATE topics SET transcript=?, modified=MAX(modified, ?), project=CASE WHEN project='' THEN ? ELSE project END,"
                          " title=CASE WHEN ?!='' AND desktop_id='' THEN ? ELSE title END WHERE key=?",
                          (p, os.path.getmtime(p), meta["cwd"], title, title, key))
            s.fill_title(key)
        keys.add(key)
    return keys


def _latest(root, prefix):
    best, bv = None, -1
    for p in glob.glob(os.path.join(root, prefix + "*.sqlite")):
        m = re.search(r"(\d+)\.sqlite$", p)
        v = int(m.group(1)) if m else 0
        if v > bv:
            best, bv = p, v
    return best


def _ro(path):
    return sqlite3.connect(f"file:{path}?mode=ro", uri=True, timeout=5)


def sync_codex(s, loc):
    root = loc["codex"]
    keys = set()
    meta = {}
    state = _latest(root, "state_")
    if state:
        try:
            src = _ro(state)
            cols = {r[1] for r in src.execute("PRAGMA table_info(threads)")}
            col = lambda c, d: f"COALESCE({c},{d})" if c in cols else d
            title = "COALESCE(NULLIF(name,''),title,'')" if "name" in cols else "COALESCE(title,'')"
            tcol = "COALESCE(updated_at_ms/1000.0," + col("updated_at", "0") + ")" if "updated_at_ms" in cols else col("updated_at", "0")
            q = (f"SELECT id,{title},{col('cwd', chr(39) * 2)},{tcol},{col('rollout_path', chr(39) * 2)},{col('archived', '0')},"
                 f"{col('first_user_message', chr(39) * 2)},{col('thread_source', chr(39) * 2)},{col('source', chr(39) * 2)} FROM threads")
            for tid, t, cwd, mod, rollout, arch, first, tsrc, srcv in src.execute(q):
                if tsrc in ("subagent", "guardian_review") or "subagent" in (srcv or "") or "guardian" in (srcv or ""):
                    continue
                key = "codex:" + tid
                rp = os.path.normpath(os.path.join(root, os.path.expanduser(rollout))) if rollout else ""
                s.upsert(key, "codex", tid, t, cwd, float(mod or 0), bool(arch), "", rp, first or "")
                meta[tid] = rp
                keys.add(key)
            src.close()
        except sqlite3.Error:
            pass
    # Bodies from the history database when present (newer Codex), otherwise rollout JSONL.
    from_history = set()
    hist = _latest(root, "thread_history_")
    if hist:
        try:
            src = _ro(hist)
            st = os.stat(hist)
            stamp = f"{st.st_size}:{st.st_mtime}"
            wal = hist + "-wal"
            if os.path.exists(wal):
                ws = os.stat(wal)
                stamp += f":{ws.st_size}:{ws.st_mtime}"
            cur = s.con.execute("SELECT head FROM cursors WHERE path=?", (hist,)).fetchone()
            if not cur or cur[0] != stamp:
                tids = [r[0] for r in src.execute("SELECT DISTINCT thread_id FROM thread_items")]
                for tid in tids:
                    key = "codex:" + tid
                    if meta and tid not in meta:
                        continue
                    s.con.execute("DELETE FROM msgs WHERE key=?", (key,))
                    rows = []
                    for (item,) in src.execute("SELECT item_json FROM thread_items WHERE thread_id=? AND item_type IN "
                                               "('userMessage','agentMessage') ORDER BY rollout_ordinal", (tid,)):
                        try:
                            m = codex_message(json.loads(item))
                        except (ValueError, TypeError):
                            m = None
                        if m:
                            rows.append((key, "user" if m[1] else "assistant", m[0][:200_000]))
                    s.con.executemany("INSERT INTO msgs(key, role, body) VALUES(?,?,?)", rows)
                    s.stats["messages"] += len(rows)
                    if key not in keys:
                        s.upsert(key, "codex", tid)
                        keys.add(key)
                    s.fill_title(key)
                s.con.execute("INSERT OR REPLACE INTO cursors VALUES(?,?,?,?,?,?)", (hist, "", 0, 0, 0, stamp))
            from_history = {r[0] for r in src.execute("SELECT DISTINCT thread_id FROM thread_items")}
            src.close()
        except sqlite3.Error:
            from_history = set()
    files = set(p for p in meta.values() if p)
    for sub in ("sessions", "archived_sessions"):
        files |= set(glob.glob(os.path.join(root, sub, "**", "*.jsonl"), recursive=True))
    for p in sorted(files):
        if not os.path.exists(p):
            continue
        tid, cwd, sub = _codex_header(p)
        if not tid or sub or tid in from_history:
            continue
        if meta and tid not in meta:
            continue
        key = "codex:" + tid
        if key not in keys:
            s.upsert(key, "codex", tid, "", cwd, os.path.getmtime(p), "/archived_sessions/" in p, "", p)
            keys.add(key)
        if s.read_jsonl(p, key, codex_message):
            s.con.execute("UPDATE topics SET modified=MAX(modified, ?) WHERE key=?", (os.path.getmtime(p), key))
            s.fill_title(key)
    return keys


def _codex_header(path):
    try:
        with open(path, "rb") as f:
            line = f.readline(131072)
        o = json.loads(line)
    except (OSError, ValueError):
        return None, "", False
    if o.get("type") != "session_meta":
        return None, "", False
    p = o.get("payload") or {}
    src = p.get("source")
    sub = isinstance(src, dict) and "subagent" in src
    return p.get("id"), p.get("cwd") or "", sub


def _workbuddy_account(root):
    p = os.path.join(root, "storage", "skeleton", "account-snapshot.json")
    try:
        if os.path.getsize(p) > 4096:
            return None
        with open(p, encoding="utf-8") as f:
            o = json.load(f)
    except (OSError, ValueError):
        return None
    if not isinstance(o, dict) or o.get("version") != 1 or not o.get("uid"):
        return None
    saved = o.get("savedAt")
    if isinstance(saved, (int, float)):
        saved = saved / 1000 if saved > 1e11 else saved
        if time.time() - saved > 30 * 86400:
            return None
    return str(o["uid"])


def _workbuddy_branch(objs):
    """Project the current branch when messages carry id / parentId (edit-and-resend creates forks)."""
    by_id = {}
    for o in objs:
        i = o.get("id") or o.get("uuid")
        if i:
            by_id[i] = o
    if len(by_id) < len(objs) * 0.8 or not objs:
        return objs
    leaf = objs[-1]
    chain, seen = [], set()
    cur = leaf
    while cur is not None:
        i = cur.get("id") or cur.get("uuid")
        if i in seen:
            break
        seen.add(i)
        chain.append(cur)
        par = cur.get("logicalParentId") or cur.get("parentId")
        cur = by_id.get(par) if par else None
    chain.reverse()
    return chain if len(chain) >= 2 else objs


def sync_workbuddy(s, loc):
    root = loc["workbuddy"]
    dbp = os.path.join(root, "workbuddy.db")
    keys = set()
    uid = _workbuddy_account(root)
    if not os.path.exists(dbp) or uid is None:
        return keys      # unknown account: never show another account's conversations
    try:
        src = _ro(dbp)
        cols = {r[1] for r in src.execute("PRAGMA table_info(sessions)")}
        col = lambda c, d: f"COALESCE({c},{d})" if c in cols else d
        transport = "AND transport='local'" if "transport" in cols else ""
        rows = src.execute(f"""SELECT id, {col('cwd', "''")}, COALESCE(NULLIF({col('custom_title', "''")},''),{col('title', "''")},''),
            MAX({col('updated_at', '0')},{col('last_activity_at', '0')},{col('created_at', '0')}), {col('status', "''")},
            {col('session_settings', "''")} FROM sessions WHERE deleted_at IS NULL AND (user_id=? OR user_id='') {transport}""",
                           (uid,)).fetchall()
        src.close()
    except sqlite3.Error:
        return keys
    sessions = {}
    for tid, cwd, title, mod, status, settings in rows:
        if not SAFE_ID.match(str(tid)):
            continue
        if settings:
            try:
                st = json.loads(settings)
                if ((st.get("conversationTags") or {}).get("wbQuickAsk")) == "1":
                    continue
            except (ValueError, AttributeError):
                continue
        sessions[tid] = (cwd, title, (mod or 0) / 1000 if (mod or 0) > 1e11 else (mod or 0), str(status).lower() == "archived")
    logs, quick = {}, set()
    for proj in glob.glob(os.path.join(root, "projects", "*")):
        for p in glob.glob(os.path.join(proj, "*")):
            b = os.path.basename(p)
            if b.endswith(".quickask"):
                quick.add(b[:-9])
            elif b.endswith(".acp-session.json"):
                try:
                    with open(p, encoding="utf-8") as f:
                        alias = json.load(f).get("acpSessionId")
                    if alias and SAFE_ID.match(alias) and os.path.isfile(os.path.join(proj, alias + ".jsonl")):
                        logs.setdefault(b[:-17], os.path.join(proj, alias + ".jsonl"))
                except (OSError, ValueError, AttributeError):
                    pass
            elif b.endswith(".jsonl") and os.path.isfile(p):
                sid = b[:-6]
                if sid not in logs or os.path.getmtime(logs[sid]) < os.path.getmtime(p):
                    logs[sid] = p
    for tid, (cwd, title, mod, arch) in sessions.items():
        if tid in quick:
            continue
        key = "workbuddy:" + tid
        log = logs.get(tid, "")
        s.upsert(key, "workbuddy", tid, title, cwd, mod, arch, "", log)
        keys.add(key)
        if log:
            _workbuddy_log(s, log, key)
            s.fill_title(key)
    return keys


def _workbuddy_log(s, path, key):
    # Branch projection needs the whole file, so re-read on any change (logs are small).
    try:
        st = os.stat(path)
    except OSError:
        return
    cur = s.con.execute("SELECT size, mtime FROM cursors WHERE path=?", (path,)).fetchone()
    if cur and cur[0] == st.st_size and cur[1] == st.st_mtime:
        s.stats["files_skipped"] += 1
        return
    objs = []
    with open(path, "rb") as f:
        for line in f:
            try:
                o = json.loads(line)
            except ValueError:
                continue
            if isinstance(o, dict) and o.get("type") == "message":
                objs.append(o)
    s.con.execute("DELETE FROM msgs WHERE key=?", (key,))
    rows = []
    for o in _workbuddy_branch(objs):
        m = workbuddy_message(o)
        if m:
            rows.append((key, "user" if m[1] else "assistant", m[0][:200_000]))
    s.con.executemany("INSERT INTO msgs(key, role, body) VALUES(?,?,?)", rows)
    s.stats["files_read"] += 1
    s.stats["messages"] += len(rows)
    s.con.execute("INSERT OR REPLACE INTO cursors VALUES(?,?,?,?,?,?)", (path, key, st.st_size, st.st_mtime, st.st_size, ""))


def sync(cfg, only=None, quiet=True):
    providers = enabled_providers(cfg, only)
    con = connect()
    s = Syncer(con)
    loc = locations()
    fns = {"claude": sync_claude, "codex": sync_codex, "workbuddy": sync_workbuddy}
    for p in providers:
        try:
            with con:
                keys = fns[p](s, loc)
                # Reconcile: drop topics whose source vanished (only for providers that were read).
                old = [r[0] for r in con.execute("SELECT key FROM topics WHERE provider=?", (p,))]
                for k in old:
                    if k not in keys:
                        con.execute("DELETE FROM msgs WHERE key=?", (k,))
                        con.execute("DELETE FROM topics WHERE key=?", (k,))
                        con.execute("DELETE FROM cursors WHERE key=?", (k,))
        except Exception as e:  # noqa: BLE001 - one failing source must not block the others
            s.errors[p] = f"{type(e).__name__}: {e}"
    con.close()
    s.stats["providers"] = providers
    if s.errors:
        s.stats["errors"] = s.errors
    return s.stats


